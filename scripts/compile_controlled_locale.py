"""Compile the CyberPanel Master controlled msgid/msgstr catalog to GNU .mo.

A small dependency-free compiler for the limited single-message .po format
generated by our own catalog. It deliberately rejects unknown PO directives
(plurals, contexts, obsolete entries) rather than silently producing a broken
translation. It NEVER writes to the installed Core unless an operator chooses
an approved destination after staging tests.
"""
from __future__ import annotations

import argparse
import io
import json
from pathlib import Path
import struct


def load_simple_po(source: str) -> dict[str, str]:
    messages: dict[str, str] = {}
    key = None
    value = None
    mode = None

    def flush():
        nonlocal key, value, mode
        if key is not None:
            if value is None or key in messages:
                raise ValueError("missing or duplicate msgstr")
            messages[key] = value
        key = value = mode = None

    for lineno, raw in enumerate(source.splitlines(), 1):
        line = raw.strip()
        if not line:
            flush()
        elif line.startswith("#"):
            if key is not None:
                raise ValueError(f"comment within msg at line {lineno}")
        elif line.startswith("msgid "):
            if key is not None:
                raise ValueError("msgid before previous message completed")
            key = json.loads(line[len("msgid "):])
            mode = "key"
        elif line.startswith("msgstr "):
            if key is None or value is not None:
                raise ValueError("msgstr without msgid")
            value = json.loads(line[len("msgstr "):])
            mode = "value"
        elif line.startswith('"'):
            fragment = json.loads(line)
            if mode == "key":
                key += fragment
            elif mode == "value":
                value += fragment
            else:
                raise ValueError("unassociated gettext continuation")
        else:
            raise ValueError(f"unsupported gettext directive at line {lineno}")
    flush()
    if "" not in messages or not messages[""]:
        raise ValueError("gettext metadata header required")
    if "charset=UTF-8\n" not in messages[""]:
        raise ValueError("gettext header must explicitly use UTF-8")
    if not any(k and v for k, v in messages.items()):
        raise ValueError("no translated messages")
    if any(k and not v for k, v in messages.items()):
        raise ValueError("catalog incomplete; refuse to advertise full coverage")
    return messages


def compile_mo(messages: dict[str, str]) -> bytes:
    if not messages:
        raise ValueError("empty catalog")
    ordered = sorted((k.encode("utf-8"), v.encode("utf-8")) for k, v in messages.items())
    count = len(ordered)
    header_size = 7 * 4
    originals_offset = header_size
    translations_offset = originals_offset + 8 * count
    strings_start = translations_offset + 8 * count
    original_locations = []
    translation_locations = []
    blob = bytearray()
    for original, translated in ordered:
        original_locations.append((len(original), strings_start + len(blob)))
        blob.extend(original + b"\0")
    for original, translated in ordered:
        translation_locations.append((len(translated), strings_start + len(blob)))
        blob.extend(translated + b"\0")
    output = bytearray(struct.pack("<7I", 0x950412DE, 0, count,
                                   originals_offset, translations_offset, 0, 0))
    for size, offset in original_locations:
        output.extend(struct.pack("<2I", size, offset))
    for size, offset in translation_locations:
        output.extend(struct.pack("<2I", size, offset))
    output.extend(blob)
    return bytes(output)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--po", type=Path, required=True)
    parser.add_argument("--mo", type=Path, required=True)
    args = parser.parse_args()
    if args.mo.exists():
        raise ValueError("refusing overwrite of existing compiled locale")
    content = args.po.read_text("utf-8")
    result = compile_mo(load_simple_po(content))
    args.mo.parent.mkdir(parents=True, exist_ok=True)
    args.mo.write_bytes(result)
    print(json.dumps({"source": str(args.po), "catalog_bytes": len(result),
                      "output": str(args.mo)}))


if __name__ == "__main__":
    main()
